//! Markdown report generation for proto dependency analysis.
//!
//! Generates detailed Markdown output from GraphModel for PR comments.

use crate::domain::{GraphModel, Node, NodeDetails, NodeType};

/// Escape special characters for Markdown table cells.
pub(crate) fn escape_markdown_cell(s: &str) -> String {
    s.replace('|', r"\|")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

/// Generates Markdown reports from proto dependency graphs.
pub struct MarkdownReporter;

impl MarkdownReporter {
    /// Generate complete Markdown report from GraphModel.
    #[must_use]
    pub fn generate(model: &GraphModel) -> String {
        let mut output = String::from("## 🪸 Coral Proto Dependency Analysis\n\n");
        output.push_str(&Self::render_overview(model));
        for (node_type, heading) in [
            (NodeType::Service, "📡 Services"),
            (NodeType::Message, "📦 Messages"),
            (NodeType::Enum, "🏷️ Enums"),
        ] {
            output.push_str(&Self::render_section(model, node_type, heading));
        }
        output.push_str("---\n*Generated by [Coral](https://github.com/daisuke8000/coral)*\n");
        output
    }

    fn render_overview(model: &GraphModel) -> String {
        let mut services = 0;
        let mut messages = 0;
        let mut enums = 0;
        let mut externals = 0;
        let mut files = std::collections::HashSet::new();

        for node in &model.nodes {
            match node.node_type {
                NodeType::Service => services += 1,
                NodeType::Message => messages += 1,
                NodeType::Enum => enums += 1,
                NodeType::External => externals += 1,
            }
            files.insert(&node.file);
        }

        format!(
            "### Overview\n\
             | Metric | Count |\n\
             |--------|-------|\n\
             | Files | {} |\n\
             | Services | {} |\n\
             | Messages | {} |\n\
             | Enums | {} |\n\
             | External | {} |\n\
             | Dependencies | {} |\n\n",
            files.len(),
            services,
            messages,
            enums,
            externals,
            model.edges.len()
        )
    }

    fn render_section(model: &GraphModel, node_type: NodeType, heading: &str) -> String {
        let items: Vec<_> = model
            .nodes
            .iter()
            .filter(|n| n.node_type == node_type)
            .collect();

        if items.is_empty() {
            return String::new();
        }

        let mut output = format!(
            "<details>\n<summary>{} ({})</summary>\n\n",
            heading,
            items.len()
        );

        for item in items {
            output.push_str(&Self::render_node(item));
        }

        output.push_str("</details>\n\n");
        output
    }

    fn render_node(node: &Node) -> String {
        let mut output = format!(
            "#### {}\n**Package**: `{}` | **File**: `{}`\n\n",
            node.label, node.package, node.file
        );

        match (&node.node_type, &node.details) {
            (NodeType::Service, NodeDetails::Service { methods, .. }) if !methods.is_empty() => {
                output.push_str("| Method | Input | Output |\n");
                output.push_str("|--------|-------|--------|\n");
                for method in methods {
                    output.push_str(&format!(
                        "| {} | {} | {} |\n",
                        escape_markdown_cell(&method.name),
                        escape_markdown_cell(&method.input_type),
                        escape_markdown_cell(&method.output_type),
                    ));
                }
            }
            (NodeType::Message, NodeDetails::Message { fields }) if !fields.is_empty() => {
                output.push_str("| # | Field | Type | Label |\n");
                output.push_str("|---|-------|------|-------|\n");
                for field in fields {
                    output.push_str(&format!(
                        "| {} | {} | {} | {} |\n",
                        field.number,
                        escape_markdown_cell(&field.name),
                        escape_markdown_cell(&field.type_name),
                        escape_markdown_cell(&field.label),
                    ));
                }
            }
            (NodeType::Enum, NodeDetails::Enum { values }) if !values.is_empty() => {
                output.push_str("| Value | Number |\n");
                output.push_str("|-------|--------|\n");
                for value in values {
                    output.push_str(&format!(
                        "| {} | {} |\n",
                        escape_markdown_cell(&value.name),
                        value.number
                    ));
                }
            }
            _ => return output,
        }
        output.push('\n');
        output
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::domain::Edge;
    use crate::domain::node::{EnumValue, FieldInfo, MethodSignature, NodeDetails};

    fn create_test_model() -> GraphModel {
        GraphModel {
            nodes: vec![
                Node::new(
                    "user.v1.UserService".to_string(),
                    NodeType::Service,
                    "user.v1".to_string(),
                    "UserService".to_string(),
                    "user/v1/user.proto".to_string(),
                    NodeDetails::Service {
                        methods: vec![
                            MethodSignature {
                                name: "GetUser".to_string(),
                                input_type: "GetUserRequest".to_string(),
                                output_type: "User".to_string(),
                            },
                            MethodSignature {
                                name: "CreateUser".to_string(),
                                input_type: "CreateUserRequest".to_string(),
                                output_type: "User".to_string(),
                            },
                        ],
                        messages: vec![],
                    },
                ),
                Node::new(
                    "user.v1.User".to_string(),
                    NodeType::Message,
                    "user.v1".to_string(),
                    "User".to_string(),
                    "user/v1/user.proto".to_string(),
                    NodeDetails::Message {
                        fields: vec![
                            FieldInfo {
                                name: "id".to_string(),
                                number: 1,
                                type_name: "string".to_string(),
                                label: "optional".to_string(),
                            },
                            FieldInfo {
                                name: "name".to_string(),
                                number: 2,
                                type_name: "string".to_string(),
                                label: "optional".to_string(),
                            },
                        ],
                    },
                ),
                Node::new(
                    "user.v1.Status".to_string(),
                    NodeType::Enum,
                    "user.v1".to_string(),
                    "Status".to_string(),
                    "user/v1/user.proto".to_string(),
                    NodeDetails::Enum {
                        values: vec![
                            EnumValue {
                                name: "UNKNOWN".to_string(),
                                number: 0,
                            },
                            EnumValue {
                                name: "ACTIVE".to_string(),
                                number: 1,
                            },
                        ],
                    },
                ),
            ],
            edges: vec![Edge::new(
                "user.v1.UserService".to_string(),
                "user.v1.User".to_string(),
            )],
            packages: vec![],
        }
    }

    #[test]
    fn test_generate_contains_header() {
        let model = create_test_model();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("## 🪸 Coral Proto Dependency Analysis"));
        assert_eq!(
            report,
            "## 🪸 Coral Proto Dependency Analysis\n\n\
             ### Overview\n\
             | Metric | Count |\n\
             |--------|-------|\n\
             | Files | 1 |\n\
             | Services | 1 |\n\
             | Messages | 1 |\n\
             | Enums | 1 |\n\
             | External | 0 |\n\
             | Dependencies | 1 |\n\n\
             <details>\n<summary>📡 Services (1)</summary>\n\n\
             #### UserService\n**Package**: `user.v1` | **File**: `user/v1/user.proto`\n\n\
             | Method | Input | Output |\n\
             |--------|-------|--------|\n\
             | GetUser | GetUserRequest | User |\n\
             | CreateUser | CreateUserRequest | User |\n\n\
             </details>\n\n\
             <details>\n<summary>📦 Messages (1)</summary>\n\n\
             #### User\n**Package**: `user.v1` | **File**: `user/v1/user.proto`\n\n\
             | # | Field | Type | Label |\n\
             |---|-------|------|-------|\n\
             | 1 | id | string | optional |\n\
             | 2 | name | string | optional |\n\n\
             </details>\n\n\
             <details>\n<summary>🏷️ Enums (1)</summary>\n\n\
             #### Status\n**Package**: `user.v1` | **File**: `user/v1/user.proto`\n\n\
             | Value | Number |\n\
             |-------|--------|\n\
             | UNKNOWN | 0 |\n\
             | ACTIVE | 1 |\n\n\
             </details>\n\n\
             ---\n*Generated by [Coral](https://github.com/daisuke8000/coral)*\n"
        );
    }

    #[test]
    fn test_generate_contains_overview() {
        let model = create_test_model();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("### Overview"));
        assert!(report.contains("| Services | 1 |"));
        assert!(report.contains("| Messages | 1 |"));
        assert!(report.contains("| Enums | 1 |"));
    }

    #[test]
    fn test_generate_contains_services() {
        let model = create_test_model();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("📡 Services (1)"));
        assert!(report.contains("#### UserService"));
        assert!(report.contains("| GetUser | GetUserRequest | User |"));
    }

    #[test]
    fn test_generate_contains_messages() {
        let model = create_test_model();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("📦 Messages (1)"));
        assert!(report.contains("#### User"));
        assert!(report.contains("| 1 | id | string | optional |"));
    }

    #[test]
    fn test_generate_contains_enums() {
        let model = create_test_model();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("🏷️ Enums (1)"));
        assert!(report.contains("#### Status"));
        assert!(report.contains("| UNKNOWN | 0 |"));
    }

    #[test]
    fn test_generate_contains_footer() {
        let model = create_test_model();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("*Generated by [Coral]"));
    }

    #[test]
    fn test_field_name_with_pipe_is_escaped() {
        let model = GraphModel {
            nodes: vec![Node::new(
                "test.Msg".to_string(),
                NodeType::Message,
                "test".to_string(),
                "Msg".to_string(),
                "test.proto".to_string(),
                NodeDetails::Message {
                    fields: vec![FieldInfo {
                        name: "field|with|pipes".to_string(),
                        number: 1,
                        type_name: "string".to_string(),
                        label: "optional".to_string(),
                    }],
                },
            )],
            edges: vec![],
            packages: vec![],
        };
        let report = MarkdownReporter::generate(&model);
        assert!(!report.contains("| field|with|pipes |"));
        assert!(report.contains(r"field\|with\|pipes"));
    }

    #[test]
    fn test_empty_model() {
        let model = GraphModel::default();
        let report = MarkdownReporter::generate(&model);
        assert!(report.contains("## 🪸 Coral"));
        assert!(report.contains("| Services | 0 |"));
        // No service/message/enum sections for empty model
        assert!(!report.contains("📡 Services"));
        assert!(!report.contains("📦 Messages"));
        assert!(!report.contains("🏷️ Enums"));
    }
}
